public class nestedLoops {

    public static void main(String[] args)
    {
        //Nested Loop is basically Loop inside another loop
        for (int i = 0 ; i < 4 ; i++){
            for (int j = 0; j < 4 ; j++){
                System.out.println(i + " ");
            }

            System.out.println(" ");
        }
    }
}
